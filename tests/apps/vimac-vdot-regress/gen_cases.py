#!/usr/bin/env python3
"""Generate VIMAC reference vectors with Python integer arithmetic."""
OPS = ['vmul','vmulh','vmulhu','vmulhsu','vmacc','vnmsac','vmadd','vnmsub',
       'vwmul','vwmulu','vwmulsu','vwmacc','vwmaccu','vwmaccsu','vsmul',
       'vmul_mask','vmacc_mask']


def signed(x, w):
    return x - (1 << w) if x >> (w - 1) else x


def pack(values, w):
    return b''.join((x & ((1 << w) - 1)).to_bytes(w // 8, 'little') for x in values)


def inputs(w):
    hi, mask = 1 << (w - 1), (1 << w) - 1
    pa = [hi, hi - 1, mask, 0, 1, hi + 1, hi - 2, 2]
    pb = [hi, mask, 2, mask, hi - 1, hi + 1, 0, 1]
    return pack([pa[i % 8] for i in range(128 // w)], w), pack([pb[i % 8] for i in range(128 // w)], w)


def reference(op, w, a, b, old, vl):
    wide = op.startswith('vw')
    ew = 2 * w if wide else w
    out = bytearray(old)
    sat = 0
    for i in range(vl):
        if op.endswith('_mask') and i % 2:
            continue
        ua = int.from_bytes(a[i*w//8:(i+1)*w//8], 'little')
        ub = int.from_bytes(b[i*w//8:(i+1)*w//8], 'little')
        sa, sb = signed(ua, w), signed(ub, w)
        acc = int.from_bytes(old[i*ew//8:(i+1)*ew//8], 'little')
        if op in ('vmul','vmul_mask','vwmul'): value = sa * sb
        elif op == 'vmulh': value = (sa * sb) >> w
        elif op == 'vmulhu': value = (ua * ub) >> w
        elif op == 'vmulhsu': value = (sa * ub) >> w
        elif op in ('vmacc','vmacc_mask','vwmacc'): value = acc + sa * sb
        elif op == 'vnmsac': value = acc - sa * sb
        elif op == 'vmadd': value = sa * acc + sb
        elif op == 'vnmsub': value = sb - sa * acc
        elif op == 'vwmulu': value = ua * ub
        elif op == 'vwmulsu': value = sa * ub
        elif op == 'vwmaccu': value = acc + ua * ub
        elif op == 'vwmaccsu': value = acc + sa * ub
        elif op == 'vsmul':
            value = (sa * sb) >> (w - 1)  # vxrm=RDN
            if value > (1 << (w - 1)) - 1:
                value = (1 << (w - 1)) - 1
                sat = 1
        else: raise ValueError(op)
        out[i*ew//8:(i+1)*ew//8] = pack([value], ew)
    return bytes(out), sat


def array(x):
    return '{' + ','.join(f'0x{b:02x}' for b in x) + '}'


old = bytes((0x3d + 17*i) & 255 for i in range(32))
print('/* Generated by gen_cases.py. */')
print('static const struct testcase cases[] = {')
for opid, op in enumerate(OPS):
    for w in (8, 16, 32, 64):
        if op.startswith('vw') and w == 64:
            continue
        a, b = inputs(w)
        vl = 128 // w - int(op.endswith('_mask'))
        expected, sat = reference(op, w, a, b, old, vl)
        vt = ((w.bit_length() - 4) << 3)
        print('  {"%s/e%d", %d, %d, %d, %d, %s, %s, %s, %s},' %
              (op, w, opid, vt, vl, sat, array(a), array(b), array(old), array(expected)))
print('};')
a, b = inputs(8)
dot = sum(signed(a[i],8)*signed(b[i],8) for i in range(16))
dotvec = pack([dot], 32) + bytes(12)
mul, _ = reference('vmul',8,a,b,old,16)
mac, _ = reference('vmacc',8,a,b,old,16)
smul, sat = reference('vsmul',8,a,b,old,16)
print('static const uint8_t mixed_a[16] __attribute__((aligned(16))) = %s;' % array(a))
print('static const uint8_t mixed_b[16] __attribute__((aligned(16))) = %s;' % array(b))
print('static const uint8_t mixed_old[32] __attribute__((aligned(16))) = %s;' % array(old))
print('static const uint8_t mixed_expected[96] = %s;' % array(dotvec+mul[:16]+dotvec+smul[:16]+mac[:16]+dotvec))
print('static const unsigned mixed_vxsat = %d;' % sat)
